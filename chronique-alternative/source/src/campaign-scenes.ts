function variantMatches(variant: CampaignVariant, game: CampaignState) {
  const known = new Set([...game.flags, ...game.history]);
  return (variant.requiresFlags || []).every((flag) => game.flags.includes(flag))
    && (variant.requiresHistory || []).every((id) => game.history.includes(id))
    && !(variant.excludesFlags || []).some((flag) => known.has(flag));
}

export function campaignSceneDialogue(scene: CampaignScene, game: CampaignState) {
  return [
    ...scene.intro,
    ...(scene.variants || []).filter((variant) => variantMatches(variant, game)).flatMap((variant) => variant.lines),
  ];
}

export function campaignSceneOutro(scene: CampaignScene) {
  return scene.outro || [];
}

export function campaignSceneById(id: string) {
  return CAMPAIGN_SCENES.find((scene) => scene.id === id);
}

